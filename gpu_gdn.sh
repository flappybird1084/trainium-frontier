#!/usr/bin/env bash
# Dev tool (local CUDA GPU): run the Trn2 vehicle on the local GPU with the v39 architecture config minus the Trainium-only
# kernel knobs, at fixed steps, single process. usage: bash gpu_gdn.sh <tag> <num_steps> [ENV=VALUE ...]
set -u
TAG=$1; STEPS=$2; shift 2
cd ~/projects/trainium-frontier
env PYTHONPATH=. NEURON_COMPETITION_R1_COMPILE=0 NEURON_COMPETITION_R1_N_EMBD=512 NEURON_COMPETITION_R1_N_HEAD=4 \
  NEURON_COMPETITION_R1_EMBED_LR_SCALE=6.0 NEURON_COMPETITION_R1_WARMDOWN=0.9 NEURON_COMPETITION_R1_SINK=logit \
  NEURON_COMPETITION_R1_SINK_IMPL=lse NEURON_COMPETITION_R1_DEVICE_BATCH=4 NEURON_COMPETITION_R1_TOTAL_BATCH=131072 \
  NEURON_COMPETITION_R1_WARMUP=50 NEURON_COMPETITION_R1_BIGRAM=18 NEURON_COMPETITION_R1_ROPE_FRAC=0.5 NEURON_COMPETITION_R1_KEY_OFFSET=1 \
  NEURON_COMPETITION_R1_EMA=0.9933 NEURON_COMPETITION_R1_EMA_START=0.85 NEURON_COMPETITION_R1_EMA_BLEND=0.35 NEURON_COMPETITION_R1_EMA_SKIP_EMBED=1 \
  NEURON_COMPETITION_R1_MATRIX_LR_SCALE=0.7 NEURON_COMPETITION_R1_ATTN_SCALE=0.1 NEURON_COMPETITION_R1_MLP_RATIO=6 NEURON_COMPETITION_R1_DEPTH=12 \
  NEURON_COMPETITION_R1_NUM_STEPS=$STEPS NEURON_COMPETITION_R1_MAX_TRAIN_SECONDS=36000 NEURON_COMPETITION_R1_OUT_DIR=out_gpu_$TAG "$@" \
  .venv/bin/python submission_raw/train3_submission.py > runs/gpu/$TAG.log 2>&1
echo "exit $?" >> runs/gpu/$TAG.log
